/**
 * Starlight's `docs` collection, loaded from the repo's `docs/` (ADR-0039) instead of
 * `src/content/docs`: titles come from each file's H1, descriptions from its first paragraph,
 * and relative links are rewritten to site or GitHub URLs (`src/lib/repo-docs.ts`).
 */

import { defineCollection } from "astro:content";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { docsSchema } from "@astrojs/starlight/schema";
import type { Loader } from "astro/loaders";
import { allPages } from "./lib/pages.ts";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");

const repoDocs: Loader = {
  name: "cloudhal-repo-docs",
  async load({ store, parseData, renderMarkdown, watcher }) {
    const sync = async () => {
      store.clear();
      const pages = allPages(REPO);
      const isFolder = (id: string) => pages.some((p) => p.id.startsWith(`${id}/`));
      for (const page of pages) {
        const data = await parseData({
          id: page.id,
          data: {
            title: page.title,
            description: page.description,
            ...(page.label || page.order !== undefined
              ? {
                  sidebar: {
                    ...(page.label ? { label: page.label } : {}),
                    ...(page.order !== undefined ? { order: page.order } : {}),
                  },
                }
              : {}),
            ...page.data,
          },
        });
        store.set({
          id: page.id,
          data,
          body: page.body,
          rendered: await renderMarkdown(page.body),
          // Starlight builds autogenerated sidebar groups from paths under its collection
          // folder; the files do not exist there (the source is `page.file`).
          filePath: `src/content/docs/${isFolder(page.id) ? `${page.id}/index` : page.id}.md`,
        });
      }
    };
    await sync();
    watcher?.add(path.join(REPO, "docs"));
    watcher?.on("change", (changed) => {
      if (changed.startsWith(path.join(REPO, "docs"))) void sync();
    });
  },
};

export const collections = {
  docs: defineCollection({ loader: repoDocs, schema: docsSchema() }),
};
