/**
 * Generates `src/i18n/generated/params.ts`, the parameters of every message key, from the English
 * catalogs (RFC-0032 §3): a plural, selectordinal or number argument is a `number`, a select
 * argument the union of its values, a plain `{name}` a string or number. `t()` checks its
 * arguments against it.
 *
 *   node apps/studio/scripts/i18n-types.ts           write the file (`pnpm gen`)
 *   node apps/studio/scripts/i18n-types.ts --check   fail if the file is stale
 *
 * Forms declared in `en.ts` (`forms`, RFC-0032 §4c) are required beside the argument they stand
 * for: a translation may use them, so every call site passes them.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { type ArgInfo, argumentsOf, compileMessage } from "@cloudhal/messages/compile";

const here = path.dirname(fileURLToPath(import.meta.url));
const I18N = path.resolve(here, "../src/i18n");
export const OUT = path.join(I18N, "generated", "params.ts");

type Tree = { [key: string]: string | Tree };
const leaves = (tree: Tree, prefix = ""): [string, string][] =>
  Object.entries(tree).flatMap(([k, v]) =>
    typeof v === "string"
      ? [[`${prefix}${k}`, v] as [string, string]]
      : leaves(v, `${prefix}${k}.`),
  );

/** The English catalogs (core and every lazy namespace), flattened to `key → text`, and the forms. */
async function english(): Promise<{
  messages: Map<string, string>;
  formsOf: (key: string) => Readonly<Record<string, readonly string[]>>;
}> {
  const core = (await import(path.join(I18N, "en.ts"))) as {
    en: Tree;
    formsOf: (key: string) => Readonly<Record<string, readonly string[]>>;
  };
  const messages = new Map(leaves(core.en));
  for (const file of readdirSync(path.join(I18N, "lazy")).filter((f) => f.endsWith(".en.ts"))) {
    const mod = (await import(path.join(I18N, "lazy", file))) as { messages: Tree };
    for (const [k, v] of leaves(mod.messages)) messages.set(k, v);
  }
  return { messages, formsOf: core.formsOf };
}

const typeOf = (info: ArgInfo): string => {
  if (info.kind === "number") return "number";
  if (info.kind === "select")
    return (info.options ?? []).map((o) => JSON.stringify(o)).join(" | ") || "string";
  return "string | number";
};
const prop = (name: string) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));

/** The generated module's text. */
export async function generate(): Promise<string> {
  const { messages, formsOf } = await english();
  const lines: string[] = [];
  for (const [key, text] of [...messages].sort(([a], [b]) => (a < b ? -1 : 1))) {
    const args = argumentsOf(compileMessage(text));
    if (args.size === 0) continue;
    const forms = formsOf(key);
    const fields = [...args].flatMap(([name, info]) =>
      [name, ...(forms[name] ?? [])].map((n) => `${prop(n)}: ${typeOf(info)}`),
    );
    lines.push(`  ${JSON.stringify(key)}: { ${fields.join("; ")} };`);
  }
  return `// Generated by apps/studio/scripts/i18n-types.ts from the English catalogs (RFC-0032 §3).
// Do not edit: change the catalogs and run \`pnpm gen\`.

/** The parameters each message key takes; keys without any are absent. */
export interface MessageParams {
${lines.join("\n")}
}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = await generate();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUT, "utf8");
    } catch {}
    if (current !== text) {
      console.error(`${path.relative(process.cwd(), OUT)} is stale: run \`pnpm gen\`.`);
      process.exit(1);
    }
  } else writeFileSync(OUT, text);
}
