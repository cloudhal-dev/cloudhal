/**
 * Generates `src/i18n/generated/params.ts`, the parameters of every message key, from the English
 * catalogs (RFC-0032 §3): a plural, selectordinal or number argument is a `number`, a select
 * argument the union of its values, a plain `{name}` a string or number. `t()` checks its
 * arguments against it.
 *
 *   node apps/studio/scripts/i18n-types.ts           write the file (`pnpm gen`)
 *   node apps/studio/scripts/i18n-types.ts --check   fail if the file is stale
 *
 * Arguments that only a translation uses (Turkish `{role}` beside English `{roles}`) are optional
 * until RFC-0032 step c declares them as forms.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { type ArgInfo, argumentsOf, compileMessage } from "@cloudhal/messages/compile";

const here = path.dirname(fileURLToPath(import.meta.url));
const I18N = path.resolve(here, "../src/i18n");
export const OUT = path.join(I18N, "generated", "params.ts");

type Tree = { [key: string]: string | Tree };
const leaves = (tree: Tree, prefix = ""): [string, string][] =>
  Object.entries(tree).flatMap(([k, v]) =>
    typeof v === "string"
      ? [[`${prefix}${k}`, v] as [string, string]]
      : leaves(v, `${prefix}${k}.`),
  );

/** Every catalog by locale: the core one plus every lazy namespace, flattened to `key → text`. */
async function catalogs(): Promise<Map<string, Map<string, string>>> {
  const out = new Map<string, Map<string, string>>();
  const add = (locale: string, tree: Tree) => {
    const map = out.get(locale) ?? new Map<string, string>();
    for (const [k, v] of leaves(tree)) map.set(k, v);
    out.set(locale, map);
  };
  for (const file of readdirSync(I18N).filter((f) => /^[\w-]+\.ts$/.test(f))) {
    if (file === "locales.ts" || file === "namespaces.ts") continue;
    const locale = file.slice(0, -3);
    const mod = (await import(path.join(I18N, file))) as Record<string, Tree>;
    add(locale, (locale === "en" ? mod.en : mod.messages) as Tree);
  }
  for (const file of readdirSync(path.join(I18N, "lazy"))) {
    const locale = file.split(".")[1] as string;
    const mod = (await import(path.join(I18N, "lazy", file))) as { messages: Tree };
    add(locale, mod.messages);
  }
  return out;
}

const typeOf = (info: ArgInfo): string => {
  if (info.kind === "number") return "number";
  if (info.kind === "select")
    return (info.options ?? []).map((o) => JSON.stringify(o)).join(" | ") || "string";
  return "string | number";
};
const prop = (name: string) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));

/** The generated module's text. */
export async function generate(): Promise<string> {
  const all = await catalogs();
  const english = all.get("en") ?? new Map<string, string>();
  const lines: string[] = [];
  for (const [key, text] of [...english].sort(([a], [b]) => (a < b ? -1 : 1))) {
    const args = argumentsOf(compileMessage(text));
    const extras = new Set<string>();
    for (const [locale, map] of all) {
      if (locale === "en") continue;
      const translated = map.get(key);
      if (translated === undefined) continue;
      for (const name of argumentsOf(compileMessage(translated)).keys())
        if (!args.has(name)) extras.add(name);
    }
    if (args.size === 0 && extras.size === 0) continue;
    const fields = [
      ...[...args].map(([name, info]) => `${prop(name)}: ${typeOf(info)}`),
      ...[...extras].sort().map((name) => `${prop(name)}?: string | number`),
    ];
    lines.push(`  ${JSON.stringify(key)}: { ${fields.join("; ")} };`);
  }
  return `// Generated by apps/studio/scripts/i18n-types.ts from the English catalogs (RFC-0032 §3).
// Do not edit: change the catalogs and run \`pnpm gen\`.

/** The parameters each message key takes; keys without any are absent. */
export interface MessageParams {
${lines.join("\n")}
}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = await generate();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUT, "utf8");
    } catch {}
    if (current !== text) {
      console.error(`${path.relative(process.cwd(), OUT)} is stale: run \`pnpm gen\`.`);
      process.exit(1);
    }
  } else writeFileSync(OUT, text);
}
