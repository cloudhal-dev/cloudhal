/**
 * Writes the MCP tool reference in packages/mcp-server/README.md (between the `tools:start` and
 * `tools:end` markers) from the tool definitions themselves, so the README never lists fewer or
 * other tools than the server serves: name, scopes, read or write, approval, first sentence.
 *
 *   node scripts/mcp-tools-doc.ts          # rewrite the README section
 *   node scripts/mcp-tools-doc.ts --check  # fail if it is stale (CI)
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { defineTools } from "../packages/mcp-server/src/tools.ts";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const README = path.join(ROOT, "packages/mcp-server/README.md");
const START = "<!-- tools:start (generated by scripts/mcp-tools-doc.ts; do not edit) -->";
const END = "<!-- tools:end -->";

type Tool = ReturnType<typeof defineTools>[number];

/** The first sentence of a description, on one line, with table pipes escaped. */
function summary(description: string): string {
  const flat = description.replace(/\s+/g, " ").trim();
  // The first ". " that does not end an abbreviation ("e.g.", "i.e.", "etc.", "vs.").
  let end = -1;
  for (const m of flat.matchAll(/[.!?](?=\s)/g)) {
    if (!/\b(e\.g|i\.e|etc|vs)$/i.test(flat.slice(0, m.index))) {
      end = m.index + 1;
      break;
    }
  }
  const first = end > 0 ? flat.slice(0, end) : flat;
  let short = first.length > 180 ? `${first.slice(0, 179).trimEnd()}…` : first;
  // A cut inside a code span would leave it open for the rest of the table.
  if ((short.match(/`/g) ?? []).length % 2 === 1) short = `${short.slice(0, -1)}\`…`;
  // `<` outside code spans would read as an HTML tag; inside them it shows as written.
  return short
    .replace(/\|/g, "\\|")
    .split("`")
    .map((part, i) => (i % 2 === 0 ? part.replace(/</g, "&lt;") : part))
    .join("`");
}

function kind(t: Tool): string {
  if (t.annotations.readOnlyHint) return "read";
  return t.annotations.destructiveHint ? "write (destructive)" : "write";
}

function approval(t: Tool): string {
  if (t.requiresApproval) return "always a person";
  if (t.classify) return "depends on the call";
  return t.annotations.readOnlyHint ? "—" : "by the key's mode";
}

export function toolsTable(tools: readonly Tool[]): string {
  const rows = tools.map(
    (t) =>
      `| \`${t.name}\` | ${t.scopes.map((s) => `\`${s}\``).join(", ")} | ${kind(t)} | ${approval(t)} | ${summary(t.description ?? "")} |`,
  );
  return [
    START,
    `**${tools.length} tools**, in the order the server lists them.`,
    "",
    "| Tool | Scopes | Kind | Approval | What it does |",
    "|---|---|---|---|---|",
    ...rows,
    END,
  ].join("\n");
}

async function render(): Promise<string> {
  const readme = await readFile(README, "utf8");
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${path.relative(ROOT, README)}: tools markers not found`);
  return readme.slice(0, a) + toolsTable(defineTools()) + readme.slice(b + END.length);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const next = await render();
  if (process.argv.includes("--check")) {
    if (next !== (await readFile(README, "utf8"))) {
      console.error(`${path.relative(ROOT, README)} is stale: run node scripts/mcp-tools-doc.ts`);
      process.exit(1);
    }
  } else {
    await writeFile(README, next);
    console.log(`wrote ${path.relative(ROOT, README)}`);
  }
}
