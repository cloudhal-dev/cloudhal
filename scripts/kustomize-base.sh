#!/usr/bin/env bash
# deploy/kustomize/base/cloudhal.yaml, rendered from the Helm chart (one source for both): release
# `cloudhal`, the chart's defaults, the Secret left to kustomize's secretGenerator, Helm's own
# labels removed. `--check` fails when the committed file differs (docker.yml runs it).
#
#   scripts/kustomize-base.sh [--check]
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/deploy/kustomize/base/cloudhal.yaml"
render() {
  echo "# Generated by scripts/kustomize-base.sh from deploy/helm/cloudhal. Do not edit."
  helm template cloudhal "$root/deploy/helm/cloudhal" --set secrets.existingSecret=cloudhal |
    grep -v -e 'helm.sh/chart:' -e 'app.kubernetes.io/managed-by: Helm' -e '^# Source:'
}
if [ "${1:-}" = "--check" ]; then
  if ! diff -u "$out" <(render); then
    echo "deploy/kustomize/base/cloudhal.yaml is stale: run scripts/kustomize-base.sh" >&2
    exit 1
  fi
else
  render > "$out"
  echo "wrote $out"
fi
