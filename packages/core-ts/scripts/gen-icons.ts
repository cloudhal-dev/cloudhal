/**
 * Writes `src/generated/icons-data.ts` from the curated list (`src/icon-names.ts`, RFC-0026 §1): each icon's
 * inner SVG and its viewBox, from Phosphor's regular weight (`@phosphor-icons/core`, a dev
 * dependency) or a vendored Simple Icons file. `test/icons.test.ts` runs `iconsData()` and fails
 * when the committed file differs.
 *
 *   node packages/core-ts/scripts/gen-icons.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ICON_SOURCES } from "../src/icon-names.ts";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const OUT = path.join(root, "src", "generated", "icons-data.ts");

/** The inner markup and viewBox of one SVG file, with titles and roles dropped. */
function parse(svg: string): { viewBox: string; body: string } {
  const open = /^<svg\b([^>]*)>/.exec(svg.trim());
  if (!open) throw new Error("not an SVG document");
  const viewBox = /viewBox="([^"]+)"/.exec(open[1] ?? "")?.[1];
  if (!viewBox) throw new Error("no viewBox");
  const body = svg
    .trim()
    .slice(open[0].length)
    .replace(/<\/svg>\s*$/, "")
    .replace(/<title>[^<]*<\/title>/g, "")
    .trim();
  if (/<script|on[a-z]+=|href=|<style|<foreignObject/i.test(body))
    throw new Error("unexpected content in an icon");
  return { viewBox, body };
}

function source(from: string): string {
  const [kind, file] = from.split(":");
  if (kind === "phosphor") {
    const file_ = createRequire(import.meta.url).resolve(
      `@phosphor-icons/core/assets/regular/${file}.svg`,
    );
    return readFileSync(file_, "utf8");
  }
  if (kind === "simple")
    return readFileSync(path.join(root, "icons", "simple-icons", `${file}.svg`), "utf8");
  throw new Error(`unknown icon source ${from}`);
}

/** The generated module's text. */
export function iconsData(): string {
  const lines = Object.entries(ICON_SOURCES).map(([name, s]) => {
    const { viewBox, body } = parse(source(s.from));
    const fields = [
      ...(viewBox === "0 0 256 256" ? [] : [`v: ${JSON.stringify(viewBox)}`]),
      `b: ${JSON.stringify(body)}`,
      ...("mirror" in s && s.mirror ? ["m: true"] : []),
    ];
    return `  ${JSON.stringify(name)}: { ${fields.join(", ")} },`;
  });
  return `// Generated by scripts/gen-icons.ts from src/icon-names.ts (RFC-0026); do not edit.
// Phosphor Icons 2.1 (MIT, https://github.com/phosphor-icons/core), regular weight; Bluesky from
// Simple Icons 16.35 (CC0, see icons/simple-icons/SOURCE.md).
import type { IconName } from "../icon-names.ts";

/** Each icon's inner SVG (\`b\`), its viewBox when not 0 0 256 256 (\`v\`), and whether it flips in RTL (\`m\`). */
export const ICON_DATA: Readonly<Record<IconName, { v?: string; b: string; m?: true }>> = {
${lines.join("\n")}
};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, iconsData());
  console.log(
    `wrote ${path.relative(process.cwd(), OUT)} (${Object.keys(ICON_SOURCES).length} icons)`,
  );
}
