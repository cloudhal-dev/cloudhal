/**
 * Writes `src/generated/icons-<weight>.ts` from the curated list (`src/icon-names.ts`, RFC-0026):
 * each icon's inner SVG and viewBox, from Phosphor's light, regular, bold and fill weights
 * (`@phosphor-icons/core`, a dev dependency), or a vendored Simple Icons file (the same in every
 * weight). `test/icons.test.ts` runs `iconsData()` and fails when a committed file differs.
 *
 *   node packages/core-ts/scripts/gen-icons.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ICON_SOURCES } from "../src/icon-names.ts";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");

export const ICON_WEIGHTS = ["light", "regular", "bold", "fill"] as const;
export type GeneratedWeight = (typeof ICON_WEIGHTS)[number];
const outFile = (weight: GeneratedWeight) =>
  path.join(root, "src", "generated", `icons-${weight}.ts`);

/** The inner markup and viewBox of one SVG file, with titles and roles dropped. */
function parse(svg: string): { viewBox: string; body: string } {
  const open = /^<svg\b([^>]*)>/.exec(svg.trim());
  if (!open) throw new Error("not an SVG document");
  const viewBox = /viewBox="([^"]+)"/.exec(open[1] ?? "")?.[1];
  if (!viewBox) throw new Error("no viewBox");
  const body = svg
    .trim()
    .slice(open[0].length)
    .replace(/<\/svg>\s*$/, "")
    .replace(/<title>[^<]*<\/title>/g, "")
    .trim();
  if (/<script|on[a-z]+=|href=|<style|<foreignObject/i.test(body))
    throw new Error("unexpected content in an icon");
  return { viewBox, body };
}

function source(from: string, weight: GeneratedWeight): string {
  const [kind, file] = from.split(":");
  if (kind === "phosphor") {
    // Phosphor names a weight's files with its suffix (`x-bold.svg`), except regular.
    const name = weight === "regular" ? file : `${file}-${weight}`;
    const resolved = createRequire(import.meta.url).resolve(
      `@phosphor-icons/core/assets/${weight}/${name}.svg`,
    );
    return readFileSync(resolved, "utf8");
  }
  if (kind === "simple")
    return readFileSync(path.join(root, "icons", "simple-icons", `${file}.svg`), "utf8");
  throw new Error(`unknown icon source ${from}`);
}

/** One weight's generated module text. */
export function iconsData(weight: GeneratedWeight): string {
  const lines = Object.entries(ICON_SOURCES).map(([name, s]) => {
    const { viewBox, body } = parse(source(s.from, weight));
    const fields = [
      ...(viewBox === "0 0 256 256" ? [] : [`v: ${JSON.stringify(viewBox)}`]),
      `b: ${JSON.stringify(body)}`,
      ...("mirror" in s && s.mirror ? ["m: true"] : []),
    ];
    return `  ${JSON.stringify(name)}: { ${fields.join(", ")} },`;
  });
  return `// Generated by scripts/gen-icons.ts from src/icon-names.ts (RFC-0026); do not edit.
// Phosphor Icons 2.1 (MIT, https://github.com/phosphor-icons/core), ${weight} weight; Bluesky from
// Simple Icons 16.35 (CC0, see icons/simple-icons/SOURCE.md).
import type { IconName } from "../icon-names.ts";

/** Each icon's inner SVG (\`b\`), its viewBox when not 0 0 256 256 (\`v\`), and whether it flips in RTL (\`m\`). */
export const ICONS: Readonly<Record<IconName, { v?: string; b: string; m?: true }>> = {
${lines.join("\n")}
};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const weight of ICON_WEIGHTS) writeFileSync(outFile(weight), iconsData(weight));
  console.log(
    `wrote src/generated/icons-{${ICON_WEIGHTS.join(",")}}.ts (${Object.keys(ICON_SOURCES).length} icons each)`,
  );
}
