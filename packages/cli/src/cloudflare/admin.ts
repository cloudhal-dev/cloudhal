/**
 * Prepares the admin Worker for wrangler: `<project>/.cloudhal/deploy/admin/` gets an entry that
 * bundles the project's skills, and a wrangler config pointing at the built Studio.
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { readSkillSources } from "@cloudhal/agent-runtime";
import {
  type AnalyticsDeployment,
  adminWorkerConfig,
  type CommentsDeployment,
  type DeploymentNames,
  type MailDeployment,
  readExistingIds,
  type SchedulerTicker,
  type SchedulesDeployment,
  writeWranglerConfig,
} from "./config.ts";

export interface PreparedAdmin {
  dir: string;
  configPath: string;
}

export async function prepareAdminWorker(options: {
  projectDir: string;
  dataDir: string;
  names: DeploymentNames;
  /** The site the site Worker serves (`CLOUDHAL_SITE_ID`; the feed check fetches only its feed). */
  siteId?: string | undefined;
  /** Built Studio (`apps/studio/dist`). */
  studioDir: string;
  skillsDir?: string | undefined;
  /** Custom domain for Studio (Cloudflare Custom Domain). */
  domain?: string | undefined;
  /** Site analytics: the Analytics SQL binding and vars (RFC-0006 §11). */
  analytics?: AnalyticsDeployment | undefined;
  /** Reader comments: the availability switch (RFC-0007 §15.3). */
  comments?: CommentsDeployment | undefined;
  /** The scheduler's ticker (RFC-0008 §8.3): the minute cron trigger (default) or the clock. */
  scheduler?: SchedulerTicker | undefined;
  /** The tick budget and the automations switch (RFC-0008 §8.2, §11.6). */
  schedules?: SchedulesDeployment | undefined;
  /** Email delivery (RFC-0011): the `send_email` binding and the sender vars. */
  mail?: MailDeployment | undefined;
}): Promise<PreparedAdmin> {
  const dir = path.join(options.projectDir, options.dataDir, "deploy", "admin");
  await mkdir(dir, { recursive: true });
  const skills = options.skillsDir ? await readSkillSources(options.skillsDir) : [];
  await writeFile(
    path.join(dir, "skills.ts"),
    `// Generated by \`cloudhal deploy\` from ${options.skillsDir ?? "(no skills)"}.\nexport default ${JSON.stringify(skills, null, 2)};\n`,
  );
  await writeFile(
    path.join(dir, "worker.ts"),
    `// Generated by \`cloudhal deploy\`.\n// The prelude must stay first (zod initialisation order; see the module).\nimport "@cloudhal/cloudflare/workerd-prelude";\nimport { createAdminWorker } from "@cloudhal/cloudflare/admin";\nimport skills from "./skills.ts";\n\n// The scheduler's Durable Object clock (RFC-0008 §8.3), declared by every deploy.\nexport { SchedulerClock } from "@cloudhal/cloudflare/admin";\n\nexport default createAdminWorker({ skills });\n`,
  );
  const configPath = path.join(dir, "wrangler.jsonc");
  const existing = await readExistingIds(configPath);
  await writeWranglerConfig(
    configPath,
    adminWorkerConfig({
      ...existing,
      ...options.names,
      ...(options.siteId ? { siteId: options.siteId } : {}),
      main: "./worker.ts",
      studioDir: path.relative(dir, options.studioDir) || ".",
      ...(options.domain ? { domain: options.domain } : {}),
      ...(options.analytics ? { analytics: options.analytics } : {}),
      ...(options.comments ? { comments: options.comments } : {}),
      ...(options.scheduler ? { scheduler: options.scheduler } : {}),
      ...(options.schedules ? { schedules: options.schedules } : {}),
      ...(options.mail ? { mail: options.mail } : {}),
    }),
    "Cloudhal admin Worker (API, auth, MCP, Studio)",
  );
  return { dir, configPath };
}
