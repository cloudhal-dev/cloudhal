/**
 * Prepares the admin Worker for wrangler: `<project>/.cloudhal/deploy/admin/` gets an entry that
 * bundles the project's skills, and a wrangler config pointing at the built Studio.
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { readSkillSources } from "@cloudhal/agent-runtime";
import {
  type AnalyticsDeployment,
  adminWorkerConfig,
  type CommentsDeployment,
  type DeploymentNames,
  type MailDeployment,
  type ObservabilityDeployment,
  readExistingIds,
  type SchedulerTicker,
  type SchedulesDeployment,
  writeWranglerConfig,
} from "./config.ts";

export interface PreparedAdmin {
  dir: string;
  configPath: string;
}

/**
 * The admin Worker's entry: the prelude first (zod initialisation order; see the module), the
 * skills as data, and the theme's block types (RFC-0015 §6) imported from the project so wrangler
 * bundles them.
 */
export function adminEntry(
  blockTypes?: string,
  themeSettings?: string,
  themeDesign = false,
): string {
  const rel = (p: string | undefined) => (p && !p.startsWith(".") ? `./${p}` : p);
  const blocksFrom = rel(blockTypes);
  const settingsFrom = rel(themeSettings);
  const options = [
    "skills",
    ...(blocksFrom ? ["blockTypes"] : []),
    ...(settingsFrom ? ["themeSettings"] : []),
    ...(themeDesign ? ["themeDesign"] : []),
  ];
  return [
    "// Generated by `cloudhal deploy`.",
    "// The prelude must stay first (zod initialisation order; see the module).",
    'import "@cloudhal/cloudflare/workerd-prelude";',
    'import { createAdminWorker } from "@cloudhal/cloudflare/admin";',
    'import skills from "./skills.ts";',
    ...(blocksFrom ? [`import { blockTypes } from ${JSON.stringify(blocksFrom)};`] : []),
    ...(settingsFrom ? [`import { themeSettings } from ${JSON.stringify(settingsFrom)};`] : []),
    // RFC-0021 §1: the theme's DESIGN.md, as text.
    ...(themeDesign ? ['import themeDesign from "./theme-design.ts";'] : []),
    "",
    "// The scheduler's Durable Object clock (RFC-0008 §8.3), declared by every deploy.",
    'export { SchedulerClock } from "@cloudhal/cloudflare/admin";',
    "// Build rooms for Studio's Build view (RFC-0020 §6), declared by every deploy.",
    'export { BuildRoom } from "@cloudhal/cloudflare/admin";',
    "",
    `export default createAdminWorker({ ${options.join(", ")} });`,
    "",
  ].join("\n");
}

export async function prepareAdminWorker(options: {
  projectDir: string;
  dataDir: string;
  names: DeploymentNames;
  /** The site the site Worker serves (`CLOUDHAL_SITE_ID`; the feed check fetches only its feed). */
  siteId?: string | undefined;
  /** Built Studio (`apps/studio/dist`). */
  studioDir: string;
  skillsDir?: string | undefined;
  /** Custom domain for Studio (Cloudflare Custom Domain). */
  domain?: string | undefined;
  /** Site analytics: the Analytics SQL binding and vars (RFC-0006 §11). */
  analytics?: AnalyticsDeployment | undefined;
  /** Reader comments: the availability switch (RFC-0007 §15.3). */
  comments?: CommentsDeployment | undefined;
  /** The scheduler's ticker (RFC-0008 §8.3): the minute cron trigger (default) or the clock. */
  scheduler?: SchedulerTicker | undefined;
  /** The tick budget and the automations switch (RFC-0008 §8.2, §11.6). */
  schedules?: SchedulesDeployment | undefined;
  /** Email delivery (RFC-0011): the `send_email` binding and the sender vars. */
  mail?: MailDeployment | undefined;
  /** In-editor AI (RFC-0016): the Workers AI binding. */
  ai?: boolean | undefined;
  /** Browser Rendering for `render_page` (RFC-0021 §4). */
  browser?: boolean | undefined;
  /** The theme's `src/blocks.ts` (RFC-0015 §6), bundled into the Worker with it. */
  blockTypes?: string | undefined;
  /** The theme's `src/settings.ts` (RFC-0017 §1), bundled the same way. */
  themeSettings?: string | undefined;
  /** The theme's DESIGN.md text (RFC-0021 §1), written next to the entry. */
  themeDesign?: string | undefined;
  /** Logs sampling and opt-in traces. */
  observability?: ObservabilityDeployment | undefined;
  /** Smart Placement for the admin Worker. */
  placement?: "smart" | undefined;
}): Promise<PreparedAdmin> {
  const dir = path.join(options.projectDir, options.dataDir, "deploy", "admin");
  await mkdir(dir, { recursive: true });
  const skills = options.skillsDir ? await readSkillSources(options.skillsDir) : [];
  await writeFile(
    path.join(dir, "skills.ts"),
    `// Generated by \`cloudhal deploy\` from ${options.skillsDir ?? "(no skills)"}.\nexport default ${JSON.stringify(skills, null, 2)};\n`,
  );
  if (options.themeDesign)
    await writeFile(
      path.join(dir, "theme-design.ts"),
      `// Generated by \`cloudhal deploy\` from the theme's src/DESIGN.md.\nexport default ${JSON.stringify(options.themeDesign)};\n`,
    );
  await writeFile(
    path.join(dir, "worker.ts"),
    adminEntry(
      options.blockTypes
        ? path.relative(dir, options.blockTypes).split(path.sep).join("/")
        : undefined,
      options.themeSettings
        ? path.relative(dir, options.themeSettings).split(path.sep).join("/")
        : undefined,
      options.themeDesign !== undefined,
    ),
  );
  const configPath = path.join(dir, "wrangler.jsonc");
  const existing = await readExistingIds(configPath);
  await writeWranglerConfig(
    configPath,
    adminWorkerConfig({
      ...existing,
      ...options.names,
      ...(options.siteId ? { siteId: options.siteId } : {}),
      main: "./worker.ts",
      studioDir: path.relative(dir, options.studioDir) || ".",
      ...(options.domain ? { domain: options.domain } : {}),
      ...(options.analytics ? { analytics: options.analytics } : {}),
      ...(options.comments ? { comments: options.comments } : {}),
      ...(options.scheduler ? { scheduler: options.scheduler } : {}),
      ...(options.schedules ? { schedules: options.schedules } : {}),
      ...(options.mail ? { mail: options.mail } : {}),
      ...(options.ai ? { ai: true } : {}),
      ...(options.browser ? { browser: true } : {}),
      ...(options.observability ? { observability: options.observability } : {}),
      ...(options.placement ? { placement: options.placement } : {}),
    }),
    "Cloudhal admin Worker (API, auth, MCP, Studio)",
  );
  return { dir, configPath };
}
